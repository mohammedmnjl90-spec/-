export function generateGeographyQuestions(): QuestionItem[] {
  const list: QuestionItem[] = [];
  let qIdx = 1;

  GEO_LANDMARKS.forEach(([name, region, desc], i) => {
    list.push(
      makeQuestion('geography', qIdx++, `أين يقع «${name}»؟`, region, [
        GEO_LANDMARKS[(i + 3) % GEO_LANDMARKS.length][1],
        GEO_LANDMARKS[(i + 7) % GEO_LANDMARKS.length][1],
        'أوقيانوسيا القطبية',
      ]),
      makeQuestion('geography', qIdx++, `ما المعلم الجغرافي: «${desc}»؟`, name, [
        GEO_LANDMARKS[(i + 2) % GEO_LANDMARKS.length][0],
        GEO_LANDMARKS[(i + 5) % GEO_LANDMARKS.length][0],
        GEO_LANDMARKS[(i + 9) % GEO_LANDMARKS.length][0],
      ]),
      makeQuestion('geography', qIdx++, `ما الذي يميز «${name}» جغرافياً؟`, desc, [
        GEO_LANDMARKS[(i + 4) % GEO_LANDMARKS.length][2],
        GEO_LANDMARKS[(i + 8) % GEO_LANDMARKS.length][2],
        GEO_LANDMARKS[(i + 12) % GEO_LANDMARKS.length][2],
      ])
    );
  });

  GEO_DIVERSE_FACTS.forEach(([q, ans, w1, w2, w3]) => {
    list.push(makeQuestion('geography', qIdx++, q, ans, [w1, w2, w3]));
  });

  const continents = ['آسيا', 'أفريقيا', 'أوروبا', 'أمريكا الشمالية', 'أمريكا الجنوبية', 'أوقيانوسيا'];
  COUNTRIES_LIST.slice(0, 35).forEach((c, i) => {
    if (!c.continentAr) return;
    const wrongConts = continents.filter((cnt) => cnt !== c.continentAr).slice(0, 3);
    list.push(
      makeQuestion(
        'geography',
        qIdx++,
        `في أي قارة تقع دولة «${c.name}»؟`,
        c.continentAr,
        wrongConts
      ),
      makeQuestion(
        'geography',
        qIdx++,
        `أي دولة تقع في «${c.continentAr}» وعاصمتها «${c.capitalAr}»؟`,
        c.name,
        [
          COUNTRIES_LIST[(i + 11) % COUNTRIES_LIST.length].name,
          COUNTRIES_LIST[(i + 23) % COUNTRIES_LIST.length].name,
          COUNTRIES_LIST[(i + 41) % COUNTRIES_LIST.length].name,
        ]
      )
    );
  });

  // Only 4 curated time-difference questions (instead of 56)
  for (const deg of [15, 30, 45, 60]) {
    const minutes = deg * 4;
    list.push(
      makeQuestion(
        'geography',
        qIdx++,
        `كم فرق التوقيت بالدقائق بين مدينتين تفصل بينهما (${deg}) درجة طول؟`,
        `${minutes} دقيقة`,
        [`${minutes + 30} دقيقة`, `${Math.max(10, minutes - 20)} دقيقة`, `${deg * 2} دقيقة`]
      )
    );
  }

  return list;
}


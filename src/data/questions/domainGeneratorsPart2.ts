export function generateHistoryQuestions(): QuestionItem[] {
  const list: QuestionItem[] = [];
  let qIdx = 1;

  HISTORICAL_DYNASTIES.forEach(([dynasty, period, capital, founders], i) => {
    list.push(
      makeQuestion('history', qIdx++, `ما عاصمة «${dynasty}»؟`, capital, [
        HISTORICAL_DYNASTIES[(i + 3) % HISTORICAL_DYNASTIES.length][2],
        HISTORICAL_DYNASTIES[(i + 7) % HISTORICAL_DYNASTIES.length][2],
        HISTORICAL_DYNASTIES[(i + 11) % HISTORICAL_DYNASTIES.length][2],
      ]),
      makeQuestion('history', qIdx++, `من أبرز قادة أو مؤسسي «${dynasty}»؟`, founders, [
        HISTORICAL_DYNASTIES[(i + 2) % HISTORICAL_DYNASTIES.length][3],
        HISTORICAL_DYNASTIES[(i + 5) % HISTORICAL_DYNASTIES.length][3],
        HISTORICAL_DYNASTIES[(i + 9) % HISTORICAL_DYNASTIES.length][3],
      ]),
      makeQuestion('history', qIdx++, `متى قامت «${dynasty}» هجرياً؟`, period, [
        HISTORICAL_DYNASTIES[(i + 4) % HISTORICAL_DYNASTIES.length][1],
        HISTORICAL_DYNASTIES[(i + 8) % HISTORICAL_DYNASTIES.length][1],
        HISTORICAL_DYNASTIES[(i + 12) % HISTORICAL_DYNASTIES.length][1],
      ])
    );
  });

  WORLD_HISTORICAL_EVENTS.forEach(([ev, year, era], i) => {
    const yearStr = year < 0 ? `${Math.abs(year)} ق.م` : `${year}م`;
    list.push(
      makeQuestion('history', qIdx++, `في أي عام وقع حدث «${ev}»؟`, yearStr, [
        `${year + 25}م`,
        `${year - 30}م`,
        `${year + 70}م`,
      ]),
      makeQuestion('history', qIdx++, `إلى أي حقبة ينتمي حدث «${ev}»؟`, era, [
        WORLD_HISTORICAL_EVENTS[(i + 3) % WORLD_HISTORICAL_EVENTS.length][2],
        WORLD_HISTORICAL_EVENTS[(i + 7) % WORLD_HISTORICAL_EVENTS.length][2],
        WORLD_HISTORICAL_EVENTS[(i + 11) % WORLD_HISTORICAL_EVENTS.length][2],
      ])
    );
  });

  HISTORY_CULTURAL_FACTS.forEach(([q, ans, w1, w2, w3]) => {
    list.push(makeQuestion('history', qIdx++, q, ans, [w1, w2, w3]));
  });

  return list;
}


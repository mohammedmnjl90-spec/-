export function generateCountriesQuestions(): QuestionItem[] {
  const list: QuestionItem[] = [];
  let qIdx = 1;

  for (let i = 0; i < COUNTRIES_LIST.length; i++) {
    const c = COUNTRIES_LIST[i];
    const w1 = COUNTRIES_LIST[(i + 5) % COUNTRIES_LIST.length];
    const w2 = COUNTRIES_LIST[(i + 13) % COUNTRIES_LIST.length];
    const w3 = COUNTRIES_LIST[(i + 27) % COUNTRIES_LIST.length];

    if (c.capitalAr) {
      list.push(
        makeQuestion(
          'countries',
          qIdx++,
          `ما عاصمة دولة «${c.name}» ${c.flag}؟`,
          c.capitalAr,
          [w1.capitalAr || 'لندن', w2.capitalAr || 'باريس', w3.capitalAr || 'روما']
        ),
        makeQuestion(
          'countries',
          qIdx++,
          `مدينة «${c.capitalAr}» هي عاصمة أي دولة؟`,
          `${c.flag} ${c.name}`,
          [`${w1.flag} ${w1.name}`, `${w2.flag} ${w2.name}`, `${w3.flag} ${w3.name}`]
        )
      );
    }

    list.push(
      makeQuestion(
        'countries',
        qIdx++,
        `ما مفتاح الاتصال الدولي لدولة «${c.name}»؟`,
        c.dialCode,
        [
          w1.dialCode !== c.dialCode ? w1.dialCode : '+991',
          w2.dialCode !== c.dialCode ? w2.dialCode : '+992',
          w3.dialCode !== c.dialCode ? w3.dialCode : '+993',
        ]
      )
    );
  }

  COUNTRIES_CULTURAL_FACTS.forEach(([q, ans, w1, w2, w3]) => {
    list.push(makeQuestion('countries', qIdx++, q, ans, [w1, w2, w3]));
  });

  return list;
}


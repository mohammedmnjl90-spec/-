export function generateArabicQuestions(): QuestionItem[] {
  const list: QuestionItem[] = [];
  let qIdx = 1;

  for (const [qText, ans, wrongs] of [
    ...ARABIC_RHETORIC_AND_GRAMMAR,
    ...ARABIC_PROVERBS_AND_POETS,
    ...ARABIC_SOUNDS_AND_ANIMALS,
  ]) {
    list.push(makeQuestion('arabic', qIdx++, qText, ans, wrongs));
  }

  ARABIC_PLURALS.forEach(([singular, plural, w1, w2, w3]) => {
    list.push(
      makeQuestion(
        'arabic',
        qIdx++,
        `ما الجمع الصحيح لكلمة «${singular}» في اللغة العربية؟`,
        plural,
        [w1, w2, w3]
      )
    );
  });

  ARABIC_SYNONYMS.forEach(([word, meaning, wrong], i) => {
    list.push(
      makeQuestion('arabic', qIdx++, `ما معنى كلمة «${word}» في المعاجم العربية؟`, meaning, [
        wrong,
        ARABIC_SYNONYMS[(i + 5) % ARABIC_SYNONYMS.length][1],
        ARABIC_SYNONYMS[(i + 11) % ARABIC_SYNONYMS.length][1],
      ]),
      makeQuestion(
        'arabic',
        qIdx++,
        `أي لفظ تراثي فصيح يطلق على «${meaning}»؟`,
        word,
        [
          ARABIC_SYNONYMS[(i + 3) % ARABIC_SYNONYMS.length][0],
          ARABIC_SYNONYMS[(i + 7) % ARABIC_SYNONYMS.length][0],
          ARABIC_SYNONYMS[(i + 13) % ARABIC_SYNONYMS.length][0],
        ]
      )
    );
  });

  return list;
}


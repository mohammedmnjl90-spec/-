export function generateIslamicQuestions(): QuestionItem[] {
  const list: QuestionItem[] = [];
  let qIdx = 1;

  for (const [qText, ans, wrongs] of [
    ...MOTHERS_OF_BELIEVERS,
    ...PROPHETS_STORIES,
    ...FIQH_AND_WORSHIP,
    ...SCHOLARS_AND_MOSQUES,
  ]) {
    list.push(makeQuestion('islamic', qIdx++, qText, ans, wrongs));
  }

  const allCompNames = COMPANIONS_FACTS.map((c) => c[0]);
  const allCompTitles = COMPANIONS_FACTS.map((c) => c[1]);

  COMPANIONS_FACTS.forEach(([name, title, desc], i) => {
    const wrongsNames = [
      allCompNames[(i + 3) % allCompNames.length],
      allCompNames[(i + 9) % allCompNames.length],
      allCompNames[(i + 17) % allCompNames.length],
    ];
    const wrongsTitles = [
      allCompTitles[(i + 4) % allCompTitles.length],
      allCompTitles[(i + 11) % allCompTitles.length],
      allCompTitles[(i + 19) % allCompTitles.length],
    ];

    list.push(
      makeQuestion('islamic', qIdx++, `من هو الصحابي الملقب بـ «${title}»؟`, name, wrongsNames),
      makeQuestion('islamic', qIdx++, `ما لقب الصحابي الجليل ${name} رضي الله عنه؟`, title, wrongsTitles),
      makeQuestion('islamic', qIdx++, `من هو الصحابي الذي عُرف بأنه: «${desc}»؟`, name, wrongsNames)
    );
  });

  ISLAMIC_EVENTS.forEach(([evName, evDate, evDesc], i) => {
    list.push(
      makeQuestion('islamic', qIdx++, `متى وقع حدث «${evName}» في السيرة النبوية؟`, evDate, [
        ISLAMIC_EVENTS[(i + 3) % ISLAMIC_EVENTS.length][1],
        ISLAMIC_EVENTS[(i + 7) % ISLAMIC_EVENTS.length][1],
        ISLAMIC_EVENTS[(i + 11) % ISLAMIC_EVENTS.length][1],
      ]),
      makeQuestion('islamic', qIdx++, `ما الغزوة أو الحدث: «${evDesc}»؟`, evName, [
        ISLAMIC_EVENTS[(i + 2) % ISLAMIC_EVENTS.length][0],
        ISLAMIC_EVENTS[(i + 5) % ISLAMIC_EVENTS.length][0],
        ISLAMIC_EVENTS[(i + 9) % ISLAMIC_EVENTS.length][0],
      ])
    );
  });

  const HIJRI_MONTHS = [
    'محرم',
    'صفر',
    'ربيع الأول',
    'ربيع الآخر',
    'جمادى الأولى',
    'جمادى الآخرة',
    'رجب',
    'شعبان',
    'رمضان',
    'شوال',
    'ذو القعدة',
    'ذو الحجة',
  ];
  HIJRI_MONTHS.forEach((mName, idx) => {
    list.push(
      makeQuestion(
        'islamic',
        qIdx++,
        `ما الشهر الهجري الذي ترتيبه رقم (${idx + 1}) في السنة الهجرية؟`,
        `شهر ${mName}`,
        [
          `شهر ${HIJRI_MONTHS[(idx + 3) % 12]}`,
          `شهر ${HIJRI_MONTHS[(idx + 6) % 12]}`,
          `شهر ${HIJRI_MONTHS[(idx + 9) % 12]}`,
        ]
      )
    );
  });

  return list;
}


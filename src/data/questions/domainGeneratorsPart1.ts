import { QuestionItem } from '../../types/game';

function makeQuestion(
  categoryId: QuestionItem['categoryId'],
  idx: number,
  question: string,
  correct: string,
  wrongPool: string[]
): QuestionItem {
  const uniqueWrongs: string[] = [];
  for (const w of wrongPool) {
    if (w !== correct && !uniqueWrongs.includes(w)) {
      uniqueWrongs.push(w);
    }
    if (uniqueWrongs.length === 3) break;
  }
  while (uniqueWrongs.length < 3) {
    uniqueWrongs.push(`خيار بديل ${uniqueWrongs.length + 1}`);
  }
  return {
    id: `${categoryId}_gen_${idx}`,
    categoryId,
    question,
    options: [correct, uniqueWrongs[0], uniqueWrongs[1], uniqueWrongs[2]],
    correctAnswer: correct,
  };
}


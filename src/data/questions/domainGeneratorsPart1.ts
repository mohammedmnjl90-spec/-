export function generateQuranQuestions(): QuestionItem[] {
  const list: QuestionItem[] = [];
  let qIdx = 1;

  for (const [qText, ans, wrongs] of QURAN_THEMATIC_QUESTIONS) {
    list.push(makeQuestion('quran', qIdx++, qText, ans, wrongs));
  }

  for (let i = 0; i < SURAHS_DATA.length; i++) {
    const [order, name, verses, revType, juz] = SURAHS_DATA[i];
    const n1 = SURAHS_DATA[(i + 7) % SURAHS_DATA.length][1];
    const n2 = SURAHS_DATA[(i + 19) % SURAHS_DATA.length][1];
    const n3 = SURAHS_DATA[(i + 37) % SURAHS_DATA.length][1];

    list.push(
      makeQuestion(
        'quran',
        qIdx++,
        `كم عدد آيات سورة ${name}؟`,
        `${verses} آية`,
        [`${verses + 5} آية`, `${Math.max(3, verses - 4)} آية`, `${verses + 12} آية`]
      ),
      makeQuestion(
        'quran',
        qIdx++,
        `ما السورة ذات الترتيب رقم (${order}) في المصحف الشريف؟`,
        `سورة ${name}`,
        [`سورة ${n1}`, `سورة ${n2}`, `سورة ${n3}`]
      )
    );

    if (i % 2 === 0 && i < SURAHS_DATA.length - 1) {
      const nextSurah = SURAHS_DATA[i + 1][1];
      list.push(
        makeQuestion(
          'quran',
          qIdx++,
          `ما السورة التي تلي سورة ${name} في ترتيب المصحف؟`,
          `سورة ${nextSurah}`,
          [`سورة ${n1}`, `سورة ${n2}`, `سورة ${n3}`]
        )
      );
    }

    if (i % 3 === 0) {
      const wrongType = revType === 'مكية' ? 'مدنية' : 'مكية';
      list.push(
        makeQuestion(
          'quran',
          qIdx++,
          `ما نوع سورة ${name} من حيث النزول، وفي أي جزء تبدأ؟`,
          `${revType} (الجزء ${juz})`,
          [
            `${wrongType} (الجزء ${juz})`,
            `${revType} (الجزء ${((juz + 5) % 30) + 1})`,
            `${wrongType} (الجزء ${((juz + 11) % 30) + 1})`,
          ]
        )
      );
    }
  }

  return list;
}


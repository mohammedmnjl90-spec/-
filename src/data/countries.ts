export const COUNTRIES_LIST: CountryInfo[] = RAW_WORLD_COUNTRIES.map(
  ([code, name, nameEn, dialCode, capitalAr, continentAr]) => ({
    code,
    name,
    nameEn,
    flag: isoToFlag(code),
    dialCode,
    capitalAr,
    continentAr,
  })
);

export function filterCountriesByQuery(query: string): CountryInfo[] {
  const q = query.trim().toLowerCase();
  if (!q) return COUNTRIES_LIST;
  return COUNTRIES_LIST.filter(
    (c) =>
      c.name.toLowerCase().includes(q) ||
      c.nameEn.toLowerCase().includes(q) ||
      c.dialCode.toLowerCase().includes(q) ||
      c.code.toLowerCase().includes(q)
  );
}
